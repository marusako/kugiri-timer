export function translate(language, key, params = {}) {
  // 知らない言語 (なくした選択肢「日本語 + English」の 'ja-en' など) は English として扱う
  const table = Object.hasOwn(MESSAGES, language) ? MESSAGES[language] : MESSAGES.en;
  const template = table[key];
  if (template === undefined) throw new Error(`unknown message key: ${key}`);
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// 初めて起動したときの言語を、Windows の言語 (例: 'ja-JP') から決める
export function detectLanguage(locale) {
  const base = String(locale ?? '').toLowerCase().split('-')[0];
  return LANGUAGES.some((l) => l.id === base) ? base : 'en';
}
